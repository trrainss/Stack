async function main() {
  for (const service of services) {
    await prisma.service.upsert({
      where: { slug: service.slug },
      update: { ...service, published: true },
      create: { ...service, published: true },
    });
  }

  for (const project of projects) {
    await prisma.project.upsert({
      where: { slug: project.slug },
      update: { ...project, published: true },
      create: { ...project, published: true },
    });
  }

  const faqCount = await prisma.faq.count();
  if (faqCount === 0) {
    await prisma.faq.createMany({
      data: faqs.map((faq) => ({ ...faq, published: true })),
    });
  }

  const stepCount = await prisma.processStep.count();
  if (stepCount === 0) {
    await prisma.processStep.createMany({
      data: processSteps.map((step) => ({ ...step, published: true })),
    });
  }

  console.log(
    `Seed complete: ${services.length} services, ${projects.length} projects, ${faqs.length} faqs, ${processSteps.length} process steps.`,
  );
}

main()
  .catch((error) => {
    console.error("Seed failed", error);
    process.exitCode = 1;
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
